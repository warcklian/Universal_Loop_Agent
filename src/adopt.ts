import { existsSync, readFileSync, writeFileSync } from "node:fs"
import { join, resolve } from "node:path"
import YAML from "yaml"
import { detectProject } from "./detector.ts"
import { generateYaml } from "./yaml-generator.ts"

const ADOPT_CANDIDATES = [
  "AGENTS.md",
  "CLAUDE.md",
  ".cursorrules",
  ".github/copilot-instructions.md",
  "GEMINI.md",
]

export interface AdoptResult {
  sourceFile: string | null
  yamlPath: string
  createdYaml: boolean
  appendedInstructions: boolean
  message: string
}

function pickBestSource(root: string, preferred?: string): string | null {
  if (preferred) {
    const p = resolve(root, preferred)
    if (existsSync(p)) return p
  }
  let best: { path: string; len: number } | null = null
  for (const rel of ADOPT_CANDIDATES) {
    const full = join(root, rel)
    if (!existsSync(full)) continue
    try {
      const len = readFileSync(full, "utf-8").trim().length
      if (!best || len > best.len) best = { path: full, len }
    } catch {
      continue
    }
  }
  return best?.path ?? null
}

/** Indent block lines for a YAML literal/folded scalar body. */
function indentBlock(block: string): string {
  return block.split("\n").map((l) => (l.length ? `  ${l}` : "")).join("\n")
}

/**
 * Append adopt text into universal_instructions without duplicating the key.
 * Prefer in-place inject for `|` / `>` scalars; otherwise YAML round-trip.
 */
export function appendAdoptInstructions(raw: string, block: string): string {
  const indented = indentBlock(block)
  const blockScalar = /^universal_instructions:\s*([|>][-+]?)[^\n]*\n/m
  if (blockScalar.test(raw)) {
    return raw.replace(blockScalar, (m) => `${m}${indented}\n`)
  }

  if (/^universal_instructions\s*:/m.test(raw)) {
    const doc = YAML.parse(raw) as Record<string, unknown>
    const prev = typeof doc.universal_instructions === "string" ? doc.universal_instructions : ""
    doc.universal_instructions = `${prev}\n${block}`.trim()
    return YAML.stringify(doc, { indent: 2, lineWidth: 120 })
  }

  return `${raw.trimEnd()}\n\nuniversal_instructions: |\n${indented}\n`
}

/**
 * Import existing editor instruction files into universal-agent.yaml
 * without destroying portable memory. Relative paths only.
 */
export function adoptProject(
  targetDir: string,
  opts: { source?: string; forceYaml?: boolean } = {},
): AdoptResult {
  const root = resolve(targetDir)
  const yamlPath = join(root, "universal-agent.yaml")
  const sourcePath = pickBestSource(root, opts.source)

  if (!sourcePath) {
    return {
      sourceFile: null,
      yamlPath,
      createdYaml: false,
      appendedInstructions: false,
      message: "No adoptable instruction file found (AGENTS.md, CLAUDE.md, .cursorrules, …)",
    }
  }

  const imported = readFileSync(sourcePath, "utf-8").trim()
  const block = [
    "",
    "# --- adopted from existing editor instructions ---",
    imported,
    "# --- end adopted ---",
    "",
  ].join("\n")

  let createdYaml = false
  if (!existsSync(yamlPath) || opts.forceYaml) {
    const project = detectProject(root)
    const config = generateYaml(project)
    const existing = config.universal_instructions ?? ""
    config.universal_instructions = `${existing}\n${block}`.trim()
    const header = [
      "# =============================================",
      `# universal-agent.yaml — ${project.name}`,
      "# Generated by uagent adopt",
      "# Edit this file, then run: uagent generate",
      "# =============================================",
      "",
    ].join("\n")
    writeFileSync(yamlPath, header + YAML.stringify(config, { indent: 2, lineWidth: 120 }), "utf-8")
    createdYaml = true
    return {
      sourceFile: sourcePath,
      yamlPath,
      createdYaml,
      appendedInstructions: true,
      message: `Created universal-agent.yaml from detection + adopted ${sourcePath}`,
    }
  }

  // Append into existing YAML as universal_instructions addition (text-safe)
  let raw = readFileSync(yamlPath, "utf-8")
  if (raw.includes("# --- adopted from existing editor instructions ---")) {
    return {
      sourceFile: sourcePath,
      yamlPath,
      createdYaml: false,
      appendedInstructions: false,
      message: "universal-agent.yaml already contains an adopt block — skipped",
    }
  }

  raw = appendAdoptInstructions(raw, block)
  writeFileSync(yamlPath, raw, "utf-8")
  return {
    sourceFile: sourcePath,
    yamlPath,
    createdYaml: false,
    appendedInstructions: true,
    message: `Appended adopt block from ${sourcePath} into universal-agent.yaml`,
  }
}
